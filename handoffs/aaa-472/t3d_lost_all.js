// #472 (i5): t3d_lost_literals over every paste file in handoffs/ against a folder of whole-BP exports. A paste is matched to the export that holds most of its node names.
// Newest paste wins per node + pin, so a later hand-off's value counts over an older one. Differences can be deliberate later edits: read the list, don't apply it blindly.
// Usage: node t3d_lost_all.js <handoffs dir> <exports dir> <out.json>
const fs = require('fs'), path = require('path');
const [, , root, expDir, outF] = process.argv;
function parse(t, onlyGraph) {
  const N = {};
  for (const m of t.matchAll(/Begin Object (?:Class=\S+ )?Name="([^"]+)"([^\n]*)\n([\s\S]*?)\n\s*End Object/g)) {
    const [, name, head, b] = m; if (!b.includes('CustomProperties Pin')) continue;
    if (onlyGraph && /ExportPath/.test(head) && /:(ExecuteUbergraph|EdGraph_|EvaluateGraph)/.test(head)) continue;
    const pins = {};
    for (const x of b.matchAll(/CustomProperties Pin \((.*)\)\s*$/gm)) {
      const p = x[1], n = (p.match(/PinName="([^"]+)"/) || [])[1]; if (!n) continue;
      pins[n] = { out: /EGPD_Output/.test(p), exec: /PinCategory="exec"/.test(p), linked: /LinkedTo=\(/.test(p), cat: (p.match(/PinCategory="(\w+)"/) || [])[1],
        dv: (p.match(/[,(]DefaultValue="([^"]*)"/) || [])[1], auto: (p.match(/AutogeneratedDefaultValue="([^"]*)"/) || [])[1] };
    }
    N[name] = { pins, fn: (b.match(/(?:FunctionReference|VariableReference)=\([^)]*MemberName="(\w+)"/) || [, ''])[1] };
  }
  return N;
}
const exports_ = {}, owner = {};
for (const f of fs.readdirSync(expDir)) if (/\.T3D$/.test(f)) { const nm = f.replace('.T3D', ''); if (/BACKUP|_BAK|_bak|backup/.test(nm)) continue; exports_[nm] = parse(fs.readFileSync(path.join(expDir, f), 'utf8'), true); for (const n of Object.keys(exports_[nm])) (owner[n] = owner[n] || []).push(nm); }
const files = [];
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) { if (!/exports|^live$|__pycache__|ue_inbox|work$/.test(e.name)) walk(p); } else if (/\.(txt|t3d)$/i.test(e.name) && !/merged|_live|manifest/.test(e.name) && fs.statSync(p).size < 6e6) files.push(p); } })(root);
files.sort((a, b) => fs.statSync(a).mtimeMs - fs.statSync(b).mtimeMs);
const want = {}; let used = 0;
const norm = v => { if (v === undefined || v === null) return ''; const f = parseFloat(v); return /^-?[\d.]+$/.test(v) && !isNaN(f) ? String(f) : String(v).toLowerCase(); };
for (const f of files) {
  const t = fs.readFileSync(f, 'utf8'); if (!t.includes('CustomProperties Pin')) continue;
  const S = parse(t), votes = {};
  for (const n of Object.keys(S)) for (const o of owner[n] || []) votes[o] = (votes[o] || 0) + 1;
  const best = Object.entries(votes).sort((a, b) => b[1] - a[1])[0]; if (!best || best[1] < 3 || best[1] < Object.keys(S).length * 0.5) continue;
  used++;
  for (const [n, s] of Object.entries(S)) for (const [pn, p] of Object.entries(s.pins)) {
    if (p.out || p.exec || p.linked || pn === 'self' || pn === 'WorldContextObject' || p.cat === 'object' || p.cat === 'class' || p.cat === 'wildcard') continue;
    const v = p.dv !== undefined ? p.dv : p.auto; if (v === undefined) continue;
    (want[best[0]] = want[best[0]] || {})[n + '|' + pn] = { v, fn: s.fn, src: path.relative(root, f) };
  }
}
const out = {}; let total = 0;
for (const [bp, m] of Object.entries(want)) {
  const L = exports_[bp], rows = [];
  for (const [k, w] of Object.entries(m)) {
    const [n, pn] = k.split('|'); const q = L[n] && L[n].pins[pn]; if (!q || q.linked) continue;
    const have = q.dv !== undefined ? q.dv : q.auto;
    if (norm(w.v) !== norm(have)) rows.push([n, pn, w.v, have, w.fn, w.src]);
  }
  if (rows.length) { out[bp] = rows; total += rows.length; const c = {}; rows.forEach(r => c[r[5]] = (c[r[5]] || 0) + 1); console.log(String(rows.length).padStart(5), bp.padEnd(28), Object.entries(c).sort((a, b) => b[1] - a[1]).slice(0, 2).map(([k, v]) => k.slice(0, 48) + ' x' + v).join(' ; ')); }
}
console.log('paste files used', used, 'of', files.length, '| total differing pins', total);
fs.writeFileSync(outF, JSON.stringify(out));
