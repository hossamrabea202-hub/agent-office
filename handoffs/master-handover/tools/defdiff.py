"""defdiff.py <paste.t3d> <live.t3d>: list unlinked input pins whose DefaultValue differs between the paste text and the live export."""
import re, sys
def parse(p):
    raw = open(p, 'rb').read()
    t = raw.decode('utf-16') if raw[:2] in (b'\xff\xfe', b'\xfe\xff') else raw.decode('utf-8', 'ignore')
    nodes = {}
    cur = None; member = ''
    for line in t.splitlines():
        s = line.strip()
        m = re.match(r'Begin Object (?:Class=\S+ )?Name="([^"]+)"', s)
        if m:
            cur = m.group(1); member = ''
            if cur not in nodes: nodes[cur] = {}
            continue
        if cur is None: continue
        mm = re.search(r'MemberName="([^"]+)"', s)
        if mm and not s.startswith('CustomProperties'): member = mm.group(1); nodes[cur]['__member'] = member
        if s.startswith('CustomProperties Pin'):
            pn = re.search(r'PinName="([^"]+)"', s).group(1)
            if 'Direction="EGPD_Output"' in s: continue
            if 'LinkedTo=(' in s: continue
            cat = re.search(r'PinCategory="([^"]*)"', s).group(1)
            dv = re.search(r'DefaultValue="([^"]*)"', s)
            ag = re.search(r'AutogeneratedDefaultValue="([^"]*)"', s)
            nodes[cur][pn] = (cat, dv.group(1) if dv else None, ag.group(1) if ag else None)
    return nodes
A = parse(sys.argv[1]); B = parse(sys.argv[2])
n = 0
for name, pins in A.items():
    if name not in B: continue
    for pn, val in pins.items():
        if pn.startswith('__'): continue
        cat, dv, ag = val
        if pn not in B[name]: continue
        cat2, dv2, ag2 = B[name][pn]
        if (dv or '') != (dv2 or ''):
            n += 1
            print('%s %s.%s [%s] paste=%r live=%r auto=%r' % (name, A[name].get('__member', ''), pn, cat, dv, dv2, ag2))
print('changed', n)
