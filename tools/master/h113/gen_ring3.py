import sys; sys.path.insert(0, '.')
from kit import *
G = Graph()
ACT, COMP, SCN = CLS('Actor'), CLS('ActorComponent'), CLS('SceneComponent')
SOLD = BPC('/Game/CastleDefender/Characters/Knight/BP_SoldierSword', 'BP_SoldierSword')
MARK = BPC('/Game/Codex/AssignmentMarkers102_v1/BP_AssignmentMarker102', 'BP_AssignmentMarker102')
MARKPATH = '/Game/Codex/AssignmentMarkers102_v1/BP_AssignmentMarker102.BP_AssignmentMarker102_C'
GS = CLS('GameplayStatics')
# ---- BeginPlay: tick every 0.5 s; spawn the marker with Owner = our soldier ----
G.node('BP', 'K2Node_Event', ['EventReference=(MemberParent=%s,MemberName="ReceiveBeginPlay")' % COMP, 'bOverrideFunction=True'],
       [{'name': 'OutputDelegate', 'cat': 'delegate', 'out': True, 'mref': '(MemberParent=%s,MemberName="ReceiveBeginPlay")' % COMP}, ex('then', True)], 0, 0)
callfn(G, 'TickInt', COMP, 'SetComponentTickInterval', [fl('TickInterval', default='0.5')], x=300, y=0, self_hidden=True)
G.link('BP', 'then', 'TickInt', 'execute')
callfn(G, 'Owner1', COMP, 'GetOwner', [ob('ReturnValue', ACT, out=True)], pure=True, const=True, x=300, y=300, self_hidden=True)
callfn(G, 'Loc1', ACT, 'K2_GetActorLocation', [st('ReturnValue', STRUCT('Vector'), out=True)], pure=True, const=True, x=600, y=300)
G.link('Owner1', 'ReturnValue', 'Loc1', 'self')
mathfn(G, 'Xf', 'MakeTransform', [st('Location', STRUCT('Vector'), default='0, 0, 0'), st('Rotation', STRUCT('Rotator'), default='0, 0, 0'), st('Scale', STRUCT('Vector'), default='1.000000,1.000000,1.000000'), st('ReturnValue', STRUCT('Transform'), out=True)], 900, 300)
G.link('Loc1', 'ReturnValue', 'Xf', 'Location')
G.node('Spawn', 'K2Node_SpawnActorFromClass', [], [ex(), ex('then', True),
    {'name': 'Class', 'cat': 'class', 'obj': ACT, 'dobj': MARKPATH},
    {'name': 'SpawnTransform', 'cat': 'struct', 'obj': STRUCT('Transform')},
    {'name': 'CollisionHandlingOverride', 'cat': 'byte', 'obj': '"/Script/CoreUObject.Enum\'/Script/Engine.ESpawnActorCollisionHandlingMethod\'"', 'default': 'AlwaysSpawn'},
    {'name': 'TransformScaleMethod', 'cat': 'byte', 'obj': '"/Script/CoreUObject.Enum\'/Script/Engine.ESpawnActorScaleMethod\'"', 'default': 'MultiplyWithRoot', 'hidden': True},
    ob('Owner', ACT), ob('ReturnValue', MARK, out=True)], 700, 0)
G.link('TickInt', 'then', 'Spawn', 'execute'); G.link('Xf', 'ReturnValue', 'Spawn', 'SpawnTransform'); G.link('Owner1', 'ReturnValue', 'Spawn', 'Owner')
varset(G, 'SetMarker', None, 'Marker', None, ob('Marker', MARK), 1300, 0, self_ctx=True)
G.link('Spawn', 'then', 'SetMarker', 'execute'); G.link('Spawn', 'ReturnValue', 'SetMarker', 'Marker')
# ---- Tick: style from the soldier's Order channel (X), alive from Dead ----
G.node('Tick', 'K2Node_Event', ['EventReference=(MemberParent=%s,MemberName="ReceiveTick")' % COMP, 'bOverrideFunction=True'],
       [{'name': 'OutputDelegate', 'cat': 'delegate', 'out': True, 'mref': '(MemberParent=%s,MemberName="ReceiveTick")' % COMP}, ex('then', True), fl('DeltaSeconds', out=True)], 0, 800)
varget(G, 'GetMarker', None, 'Marker', None, ob('Marker', MARK), 0, 1000, self_ctx=True)
callfn(G, 'MValid', CLS('KismetSystemLibrary'), 'IsValid', [ob('Object', '"/Script/CoreUObject.Class\'/Script/CoreUObject.Object\'"'), bo('ReturnValue', out=True)], pure=True, x=250, y=1000, self_hidden=True)
G.link('GetMarker', 'Marker', 'MValid', 'Object')
branch(G, 'IfMarker', 300, 800)
G.link('Tick', 'then', 'IfMarker', 'execute'); G.link('MValid', 'ReturnValue', 'IfMarker', 'Condition')
callfn(G, 'Owner2', COMP, 'GetOwner', [ob('ReturnValue', ACT, out=True)], pure=True, const=True, x=300, y=1200, self_hidden=True)
cast(G, 'AsSoldier', SOLD, 'AsBP Soldier Sword', 600, 800)
G.link('IfMarker', 'then', 'AsSoldier', 'execute'); G.link('Owner2', 'ReturnValue', 'AsSoldier', 'Object')
# order channel
varget(G, 'GetOrder', SOLD, 'Order', SOLD, ob('Order', SCN), 900, 1150)
G.link('AsSoldier', 'AsBP Soldier Sword', 'GetOrder', 'self')
varget(G, 'OrdLoc', SCN, 'RelativeLocation', SCN, st('RelativeLocation', STRUCT('Vector')), 1150, 1150)
G.link('GetOrder', 'Order', 'OrdLoc', 'self')
mathfn(G, 'Brk', 'BreakVector', [st('InVec', STRUCT('Vector'), default='0, 0, 0'), fl('X', out=True, sub='double'), fl('Y', out=True, sub='double'), fl('Z', out=True, sub='double')], 1400, 1150)
G.link('OrdLoc', 'RelativeLocation', 'Brk', 'InVec')
mathfn(G, 'Rnd', 'Round', [fl('A', default='0.0', sub='double'), it('ReturnValue', out=True)], 1650, 1150)
G.link('Brk', 'X', 'Rnd', 'A')
mathfn(G, 'Clamp', 'Clamp', [it('Value', default='0'), it('Min', default='0'), it('Max', default='7'), it('ReturnValue', out=True)], 1850, 1150)
G.link('Rnd', 'ReturnValue', 'Clamp', 'Value')
varget(G, 'GetLast', None, 'LastStyle', None, it('LastStyle'), 1850, 1350, self_ctx=True)
mathfn(G, 'Changed', 'NotEqual_IntInt', [it('A', default='0'), it('B', default='0'), bo('ReturnValue', out=True)], 2100, 1200)
G.link('Clamp', 'ReturnValue', 'Changed', 'A'); G.link('GetLast', 'LastStyle', 'Changed', 'B')
branch(G, 'IfChanged', 1000, 800)
G.link('AsSoldier', 'then', 'IfChanged', 'execute'); G.link('Changed', 'ReturnValue', 'IfChanged', 'Condition')
varset(G, 'SetLast', None, 'LastStyle', None, it('LastStyle', default='0'), 1300, 800, self_ctx=True)
G.link('IfChanged', 'then', 'SetLast', 'execute'); G.link('Clamp', 'ReturnValue', 'SetLast', 'LastStyle')
callfn(G, 'SetStyle', MARK, 'SetAssignment102', [it('SemanticStyle', default='0')], x=1650, y=800)
G.link('SetLast', 'then', 'SetStyle', 'execute'); G.link('GetMarker', 'Marker', 'SetStyle', 'self'); G.link('SetLast', 'Output_Get', 'SetStyle', 'SemanticStyle')
# dead -> SetMarkerAlive102(false) once (NotifiedDead latch)
# no Dead member on the soldier: a dead soldier ragdolls, so Mesh.IsSimulatingPhysics is the 'dead' signal
varget(G, 'GetMesh', CLS('Character'), 'Mesh', CLS('Character'), ob('Mesh', CLS('SkeletalMeshComponent')), 700, 1600)
G.link('AsSoldier', 'AsBP Soldier Sword', 'GetMesh', 'self')
callfn(G, 'GetDead', CLS('PrimitiveComponent'), 'IsSimulatingPhysics', [{'name': 'BoneName', 'cat': 'name', 'default': 'None'}, bo('ReturnValue', out=True)], pure=True, const=True, x=950, y=1600)
G.link('GetMesh', 'Mesh', 'GetDead', 'self')
varget(G, 'GetNotified', None, 'NotifiedDead', None, bo('NotifiedDead'), 900, 1750, self_ctx=True)
mathfn(G, 'NotN', 'Not_PreBool', [bo('A', default='false'), bo('ReturnValue', out=True)], 1150, 1750)
G.link('GetNotified', 'NotifiedDead', 'NotN', 'A')
mathfn(G, 'DeadNow', 'BooleanAND', [bo('A', default='false'), bo('B', default='false'), bo('ReturnValue', out=True)], 1400, 1650)
G.link('GetDead', 'ReturnValue', 'DeadNow', 'A'); G.link('NotN', 'ReturnValue', 'DeadNow', 'B')
branch(G, 'IfDead', 2000, 800)
G.link('IfChanged', 'else', 'IfDead', 'execute'); G.link('SetStyle', 'then', 'IfDead', 'execute'); G.link('DeadNow', 'ReturnValue', 'IfDead', 'Condition')
varset(G, 'SetNotified', None, 'NotifiedDead', None, bo('NotifiedDead', default='true'), 2300, 800, self_ctx=True)
G.link('IfDead', 'then', 'SetNotified', 'execute')
callfn(G, 'SetAlive', MARK, 'SetMarkerAlive102', [bo('Alive', default='false')], x=2600, y=800)
G.link('SetNotified', 'then', 'SetAlive', 'execute'); G.link('GetMarker', 'Marker', 'SetAlive', 'self')
open('BPC_AssignmentRing_graph_v3.txt', 'w').write(G.render())
print('nodes', len(G.nodes), 'links', len(G.links))
